#!/usr/bin/env bash
#
# DEV-ONLY: install tracked shims so the app can run without a full
# chip-core wasm build, Firebase credentials, or a real catalog.
#
# Everything this script touches is either gitignored or backed up first.
# Run `dev/remove.sh` to undo all of it.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

echo "[dev] Applying development shims..."

# 1. chip-core stub -> src/chip-core.js (gitignored). Only when there is no core:
# a built core's JS glue is real audio, and overwriting it with this no-op shim
# silently kills playback in a live tree. `bringup` copies a real core after this.
if [ ! -f src/chip-core.js ]; then
  cp dev/shims/chip-core.js src/chip-core.js
  echo "[dev]   installed src/chip-core.js (stub)"
else
  echo "[dev]   kept existing src/chip-core.js (not replacing a built core with the stub)"
fi

# 2. Firebase placeholder -> src/config/firebaseConfig.js (gitignored)
if [ -f src/config/firebaseConfig.js ] && [ ! -f src/config/firebaseConfig.js.dev-backup ]; then
  cp src/config/firebaseConfig.js src/config/firebaseConfig.js.dev-backup
  echo "[dev]   backed up existing src/config/firebaseConfig.js"
fi
cp dev/shims/firebaseConfig.js src/config/firebaseConfig.js
echo "[dev]   installed src/config/firebaseConfig.js (placeholder)"

# 3. Auth bypass -> server/middleware/auth.dev.js (untracked, gitignored).
# server/index.js requires DEV_AUTH_MODULE when set, so the real middleware is
# never patched.
cp dev/shims/server-auth.js server/middleware/auth.dev.js
echo "[dev]   staged server/middleware/auth.dev.js (bypass)"

# 4. Dev-only deltas on tracked files (reversible; dev/remove.sh reverts them):
#    server/index.js -- the auth bypass, per-target ports, the dev HTML injection;
#    src/components/UserProvider.js -- the fake dev user, so favorites work in a
#    worktree whose UserProvider is upstream's.
node dev/patch-server.js
node dev/patch-client.js

# Browser test hooks (window.__cpDev). Staged as an untracked, gitignored
# module and picked up by the dev webpack entry; no tracked file is patched.
cp dev/shims/devtools.js src/chip-player-devtools.js
echo "[dev]   staged src/chip-player-devtools.js"

# Clip-recording hooks (window.__cpRec): audio mirror + sync flash + settings
# pinning for dev/record/. Staged the same way as the devtools shim.
cp dev/shims/recorder.js src/chip-player-record.js
echo "[dev]   staged src/chip-player-record.js"

# 6. Seed sqlite databases (catalog.db is built separately by build-music.js)
node dev/seed-dbs.js

# 7. server/.env.local (gitignored)
if [ ! -f server/.env.local ]; then
  cat > server/.env.local <<EOF
# DEV-ONLY, generated by dev/apply.sh
BROWSE_LOCAL_FILESYSTEM=false
LOCAL_CATALOG_ROOT='$ROOT/catalog'
LOCAL_SOUNDFONT_ROOT='$ROOT/public/soundfonts'
LOCAL_CLIENT_BUILD_ROOT='$ROOT/public'
EOF
  echo "[dev]   wrote server/.env.local"
else
  echo "[dev]   server/.env.local already exists; leaving as-is"
fi
# Ensure the auth override is set (older .env.local files predate it).
if ! grep -q '^DEV_AUTH_MODULE=' server/.env.local; then
  echo "DEV_AUTH_MODULE='./middleware/auth.dev.js'" >> server/.env.local
  echo "[dev]   added DEV_AUTH_MODULE to server/.env.local"
fi

# 8. Sample catalog (gitignored) + catalog db. The canonical sample is
# dev/sample.manifest -- one file per engine family plus the harness fixtures --
# and dev/sample.sh places each by symlink/hardlink/copy and indexes it. A worktree
# gets that, never some other branch's collection.
mkdir -p catalog
if ! bash dev/sample.sh seed; then
  echo "[dev]   WARNING: sample seeding failed; catalog/ may be incomplete."
fi
if [ ! -f server/catalog.db ]; then
  echo "[dev]   building server/catalog.db..."
  node scripts/build-music.js || echo "[dev]   WARNING: build-music.js failed; add files to catalog/ and rerun."
fi

echo "[dev] Done. Start with: npm run dev"
